#!/usr/bin/env python3
"""Generates src/casefold_data.rs, the tables of DashFS caseless names.

A name's key is NFD(casefold(NFD(c))) for each character, then canonical ordering of the combining marks. The
tables are frozen in the repository: a newer Unicode must not change the key of a name already on disk. Changing
them means a new DashFS version.

Usage: python3 tools/gen_casefold.py > src/casefold_data.rs
Also: python3 tools/gen_casefold.py --vectors N SEED > tests/casefold_vectors.txt (strings and keys to check
the Rust code against Python).
"""
import random
import sys
import unicodedata

HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def chars():
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        yield cp


def fold(text):
    return unicodedata.normalize("NFD", unicodedata.normalize("NFD", text).casefold())


def key(text):
    out = []
    for ch in text:
        out.extend(fold(ch))
    # Canonical ordering: a stable sort of each run of marks (combining class above 0).
    i = 0
    while i < len(out):
        if unicodedata.combining(out[i]) == 0:
            i += 1
            continue
        j = i
        while j < len(out) and unicodedata.combining(out[j]) != 0:
            j += 1
        out[i:j] = sorted(out[i:j], key=unicodedata.combining)
        i = j
    return "".join(out)


def tables():
    folds = []
    for cp in chars():
        if HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue
        ch = chr(cp)
        f = fold(ch)
        if f != ch:
            folds.append((cp, f))
    classes = []
    for cp in chars():
        ccc = unicodedata.combining(chr(cp))
        if ccc == 0:
            continue
        if classes and classes[-1][1] == cp - 1 and classes[-1][2] == ccc:
            classes[-1][1] = cp
        else:
            classes.append([cp, cp, ccc])
    return folds, classes


def emit():
    folds, classes = tables()
    data = []
    index = []
    offset = 0
    for cp, f in folds:
        b = f.encode("utf-8")
        assert len(b) < 256 and offset < 1 << 24
        index.append((cp, offset, len(b)))
        data.append(f)
        offset += len(b)
    text = "".join(data)
    print("// Generated by tools/gen_casefold.py from Unicode %s. Do not edit: see that script." %
          unicodedata.unidata_version)
    print()
    print('pub const UNICODE_VERSION: &str = "%s";' % unicodedata.unidata_version)
    print()
    print("/// Characters whose key is not themselves: (code point, start in FOLD_TEXT << 8 | length in bytes).")
    print("pub static FOLD_INDEX: [(u32, u32); %d] = [" % len(index))
    for cp, off, ln in index:
        print("    (0x%X, 0x%X)," % (cp, off << 8 | ln))
    print("];")
    print()
    print("pub static FOLD_TEXT: &str = \"%s\";" %
          "".join(c if 0x20 <= ord(c) < 0x7F and c not in '"\\' else "\\u{%X}" % ord(c) for c in text))
    print()
    print("/// Canonical combining classes above 0: (first, last, class).")
    print("pub static COMBINING: [(u32, u32, u8); %d] = [" % len(classes))
    for a, b, c in classes:
        print("    (0x%X, 0x%X, %d)," % (a, b, c))
    print("];")


def vectors(n, seed):
    rnd = random.Random(seed)
    pools = [
        "abcxyzABCXYZ0189 ._-",
        "áéíóúÁÉÍÓÚñÑüÜçÇàèÀÈ",
        "ßẞſΣσςΐΰİıﬀﬁǅǄǆ",
        "̧̛̣́̀̈̃ͅ",
        "ΑαΩωЖжЯяԱաᏀꭰ𐐀𐐨",
        "가각힣ㄱ각",
        "日本語🙂𝔄",
    ]
    print("# Generated by tools/gen_casefold.py --vectors %d %d (Unicode %s): name TAB key, both as code points." %
          (n, seed, unicodedata.unidata_version))
    for _ in range(n):
        s = "".join(rnd.choice(rnd.choice(pools)) for _ in range(rnd.randint(1, 12)))
        k = key(s)
        print(" ".join("%X" % ord(c) for c in s) + "\t" + " ".join("%X" % ord(c) for c in k))


if __name__ == "__main__":
    if len(sys.argv) == 4 and sys.argv[1] == "--vectors":
        vectors(int(sys.argv[2]), int(sys.argv[3]))
    else:
        emit()

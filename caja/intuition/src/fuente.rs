//! La fuente del sistema: "topaz.font" de 8 puntos, dibujada aquí (sala limpia: nada de la fuente de la ROM).
//!
//! Solo se copian las medidas, que son interfaz (los programas cuentan con ellas): celdas de 8 x 8, ancho fijo y
//! la línea base en la fila 6. Los dibujos son propios, de trazo de un punto. Lleva ASCII (32 a 126) y lo de
//! Latin-1 que hace falta para escribir en castellano, catalán, portugués, francés o alemán, el espacio duro (MUI
//! lo usa para los tabuladores), × ÷ ± ¬ « » © ® § £; lo demás sale como una caja.
//!
//! En la caja es una `struct TextFont` de verdad, en la memoria del 68k, con su `tf_CharData` y su
//! `tf_CharLoc`: `Text` la dibuja leyendo esa estructura, como cualquier otra fuente que monte un programa.


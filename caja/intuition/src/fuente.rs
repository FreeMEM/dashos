/// El carácter de la caja (los que no tienen dibujo).
pub(crate) const NO_HAY: u32 = 0x100;

/// Los glifos de la hoja: (carácter Latin-1, o `NO_HAY`; sus 8 filas, el bit 7 a la izquierda).
pub(crate) fn glifos() -> Vec<(u32, [u8; 8])> {
    let mut v = Vec::new();
    let mut lineas = HOJA.lines().filter(|l| !l.trim().is_empty());
    while let Some(cab) = lineas.next() {
        let chars: Vec<u32> = cab
            .split_whitespace()
            .map(|t| match t {
                "SP" => 32,
                // El espacio duro (0xA0): split_whitespace se lo comería.
                "NB" => 0xA0,
                "NO" => NO_HAY,
                _ => t.chars().next().map(|c| c as u32).unwrap_or(NO_HAY),
            })
            .collect();
        let mut filas = [[0u8; 8]; 8];
        for fila in filas.iter_mut() {
            let l = lineas.next().unwrap_or("");
            for (i, bloque) in l.split_whitespace().enumerate().take(8) {
                let mut b = 0u8;
                for (j, c) in bloque.bytes().enumerate().take(8) {
                    if c == b'#' {
                        b |= 0x80 >> j;
                    }
                }
                fila[i] = b;
            }
        }
        for (i, &c) in chars.iter().enumerate() {
            let mut g = [0u8; 8];
            for (f, fila) in filas.iter().enumerate() {
                g[f] = fila[i];
            }
            v.push((c, g));
        }
    }
    v
}

/// Monta la `struct TextFont` de topaz/8 en la memoria del 68k (del sistema: no se libera nunca) y devuelve su
/// dirección. `LoChar` 32, `HiChar` 255; los que no tienen dibujo apuntan a la caja, que va también al final
/// (el glifo de "no definido" de `tf_CharLoc`).
pub(crate) fn construir<M: Memoria>(ex: &mut Exec<M>) -> Result<u32, Fallo> {
    let g = glifos();
    let caja = g.iter().position(|(c, _)| *c == NO_HAY).unwrap_or(0) as u32;
    let modulo = (g.len() as u32 + 1) & !1;
    let (lo, hi) = (32u32, 255u32);
    let entradas = hi - lo + 2;

    let f = ex.reservar(tf::TAMANO, memf::CLEAR)?;
    let datos = ex.reservar(modulo * ALTO, memf::CLEAR)?;
    let loc = ex.reservar(entradas * 4, memf::CLEAR)?;
    let nombre = ex.cadena_nueva(NOMBRE.as_bytes())?;

    for (i, (_, filas)) in g.iter().enumerate() {
        for (y, b) in filas.iter().enumerate() {
            ex.e8(datos + y as u32 * modulo + i as u32, *b)?;
        }
    }
    for c in lo..=hi + 1 {
        let i = g.iter().position(|(x, _)| *x == c).map(|i| i as u32).unwrap_or(caja);
        ex.e32(loc + (c - lo) * 4, (i * ANCHO) << 16 | ANCHO)?;
    }
    ex.e8(f + node::LN_TYPE, nt::FONT)?;
    ex.e32(f + node::LN_NAME, nombre)?;
    ex.e16(f + message::MN_LENGTH, tf::TAMANO as u16)?;
    ex.e16(f + tf::TF_YSIZE, ALTO as u16)?;
    ex.e8(f + tf::TF_STYLE, 0)?;
    ex.e8(f + tf::TF_FLAGS, tf::FPF_ROMFONT | tf::FPF_DESIGNED)?;
    ex.e16(f + tf::TF_XSIZE, ANCHO as u16)?;
    ex.e16(f + tf::TF_BASELINE, BASE as u16)?;
    ex.e16(f + tf::TF_BOLDSMEAR, 1)?;
    ex.e16(f + tf::TF_ACCESSORS, 1)?;
    ex.e8(f + tf::TF_LOCHAR, lo as u8)?;
    ex.e8(f + tf::TF_HICHAR, hi as u8)?;
    ex.e32(f + tf::TF_CHARDATA, datos)?;
    ex.e16(f + tf::TF_MODULO, modulo as u16)?;
    ex.e32(f + tf::TF_CHARLOC, loc)?;
    Ok(f)
}

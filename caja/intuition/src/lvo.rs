/// La fila de una función por su nombre, en tiempo de compilación (para los `match` del despacho).
pub const fn fila(tabla: &[(&str, &str)], nombre: &str) -> usize {
    let mut i = 0;
    while i < tabla.len() {
        if iguales(tabla[i].0, nombre) {
            return i;
        }
        i += 1;
    }
    panic!("función que no está en la tabla");
}

const fn iguales(a: &str, b: &str) -> bool {
    let (a, b) = (a.as_bytes(), b.as_bytes());
    if a.len() != b.len() {
        return false;
    }
    let mut i = 0;
    while i < a.len() {
        if a[i] != b[i] {
            return false;
        }
        i += 1;
    }
    true
}

/// El LVO (negativo) de la fila `i`.
pub const fn lvo(i: usize) -> i32 {
    -30 - 6 * i as i32
}

/// La fila de una función de graphics por su nombre.
pub fn graphics(nombre: &str) -> Option<usize> {
    GRAPHICS.iter().position(|(n, _)| *n == nombre)
}

/// La fila de una función de intuition por su nombre.
pub fn intuition(nombre: &str) -> Option<usize> {
    INTUITION.iter().position(|(n, _)| *n == nombre)
}
